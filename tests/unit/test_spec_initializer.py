@pytest.mark.skipif(not hasattr(os, "symlink"), reason="symlinks are unavailable")
def test_classification_rejects_symlinked_managed_path(tmp_path: Path) -> None:
    outside = tmp_path.parent / f"{tmp_path.name}-outside"
    outside.mkdir()
    (outside / "edited.md").write_bytes(b"user data")
    managed = tmp_path / ".specify" / "templates"
    managed.parent.mkdir()
    try:
        managed.symlink_to(outside, target_is_directory=True)
    except OSError as exc:
        pytest.skip(f"cannot create symlink: {exc}")

    with pytest.raises(ManifestError, match="symlink"):
        classify_files(tmp_path, None, [".specify/templates/edited.md"])


@pytest.mark.skipif(not hasattr(os, "symlink"), reason="symlinks are unavailable")
def test_load_manifest_rejects_symlinked_manifest(tmp_path: Path) -> None:
    specify = tmp_path / ".specify"
    specify.mkdir()
    outside = tmp_path / "outside.json"
    outside.write_bytes(OwnershipManifest("0.1.0", ()).to_bytes())
