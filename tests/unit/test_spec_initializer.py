"""Tests for the Spec Kit initializer ownership manifest contract."""

from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path

import pytest

from hybrid_sdlc.spec_initializer import (
    MANIFEST_RELATIVE_PATH,
    FileOwnership,
    ManagedFile,
    ManifestError,
    OwnershipManifest,
    classify_files,
    load_manifest,
    save_manifest,
    sha256_bytes,
    validate_managed_path,
)


def _record(path: str, content: bytes, source: bytes | None = None) -> ManagedFile:
    return ManagedFile(
        path=path,
        sha256=sha256_bytes(content),
        source_sha256=sha256_bytes(source) if source is not None else None,
    )


def test_manifest_serialization_is_deterministic_and_round_trips() -> None:
    first = _record(".specify/templates/spec-template.md", b"installed", b"source")
    second = _record(".specify/memory/constitution.md", b"rules")
    manifest = OwnershipManifest("0.1.0", (first, second))

    serialized = manifest.to_bytes()

    assert serialized.endswith(b"\n")
    assert serialized == manifest.to_bytes()
    assert OwnershipManifest.from_bytes(serialized) == manifest
    assert serialized.index(b"constitution.md") < serialized.index(b"spec-template.md")


def test_manifest_load_save_uses_dedicated_path_and_raw_hashes(tmp_path: Path) -> None:
    managed_path = ".specify/templates/spec-template.md"
    content = b"line one\r\nline two\n"
    destination = tmp_path.joinpath(*managed_path.split("/"))
    destination.parent.mkdir(parents=True)
    destination.write_bytes(content)
    manifest = OwnershipManifest("0.1.0", (_record(managed_path, content),))

    manifest_path = save_manifest(tmp_path, manifest)

    assert manifest_path.relative_to(tmp_path).as_posix() == MANIFEST_RELATIVE_PATH
    assert manifest_path.read_bytes() == manifest.to_bytes()
    assert load_manifest(tmp_path) == manifest


def test_classify_distinguishes_generated_modified_untracked_and_missing(tmp_path: Path) -> None:
    paths = [
        ".specify/templates/generated.md",
        ".specify/templates/customized.md",
        ".specify/templates/untracked.md",
        ".specify/memory/removed.md",
        ".specify/templates/not-created.md",
    ]
    contents = {
        paths[0]: b"generated bytes",
        paths[1]: b"user edit",
        paths[2]: b"created by user",
    }
    for relpath, content in contents.items():
        target = tmp_path.joinpath(*relpath.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    manifest = OwnershipManifest(
        "0.1.0",
        (
            _record(paths[0], contents[paths[0]]),
            _record(paths[1], b"original"),
            _record(paths[3], b"gone"),
        ),
    )

    states = classify_files(tmp_path, manifest, paths)

    assert states == {
        paths[0]: FileOwnership.UNCHANGED_GENERATED,
        paths[1]: FileOwnership.MODIFIED_USER_OWNED,
        paths[2]: FileOwnership.UNTRACKED_USER_OWNED,
        paths[3]: FileOwnership.MISSING,
        paths[4]: FileOwnership.MISSING,
    }


